import 'dart:io';
import 'dart:ui' show Locale;

import 'package:youtube_explode_dart/youtube_explode_dart.dart';

abstract class Subtitles {
  static const _exts = {'srt', 'vtt', 'ass', 'ssa'};
  static final _lang = RegExp(r'^[A-Za-z]{2,3}(-[A-Za-z0-9]{2,8})*$');

  static List<String> wanted(Locale device) => {device.languageCode.toLowerCase(), 'en'}.toList();

  static List<ClosedCaptionTrackInfo> pick(Iterable<ClosedCaptionTrackInfo> tracks, List<String> langs) {
    final srv3 = tracks.where((t) => t.format.formatCode == ClosedCaptionFormat.srv3.formatCode).toList();
    return [
      for (final lang in langs)
        if (srv3.where((t) => _matches(t.language.code, lang)).toList() case final m when m.isNotEmpty)
          m.firstWhere((t) => !t.isAutoGenerated, orElse: () => m.first),
    ];
  }

  static List<ClosedCaptionTrackInfo> forWatching(Iterable<ClosedCaptionTrackInfo> tracks, List<String> langs) {
    final wanted = pick(tracks, langs);
    if (wanted.isNotEmpty) return wanted;
    final srv3 = tracks.where((t) => t.format.formatCode == ClosedCaptionFormat.srv3.formatCode).toList();
    if (srv3.isEmpty) return const [];
    return [srv3.firstWhere((t) => !t.isAutoGenerated, orElse: () => srv3.first)];
  }

  static bool _matches(String code, String lang) {
    final c = code.toLowerCase();
    return c == lang || c.startsWith('$lang-');
  }

  static String sidecarPath(String video, String lang, [String ext = 'srt']) => '${_base(video)}.$lang.$ext';

  static Map<String, String> fromTracks(Object? raw) {
    final out = <String, String>{};
    if (raw is! List) return out;
    for (final t in raw.whereType<Map>()) {
      final url = t['url'], lang = t['lang'], kind = t['kind'] ?? 'subtitles';
      if (url is! String || !url.startsWith('http') || (kind != 'subtitles' && kind != 'captions')) continue;
      out.putIfAbsent(lang is String && _lang.hasMatch(lang) ? lang : 'und', () => url);
    }
    return out;
  }

  static bool looksLikeSubtitles(String text) {
    final t = text.trimLeft();
    return !t.startsWith('<') && (t.contains('-->') || t.startsWith('[Script Info]'));
  }

  static String extOf(String url) {
    final path = Uri.tryParse(url)?.path.toLowerCase() ?? '';
    final ext = path.substring(path.lastIndexOf('.') + 1);
    return _exts.contains(ext) ? ext : 'vtt';
  }

  static List<String> sidecarsOf(String video) {
    final base = _base(video);
    final dir = base.substring(0, base.lastIndexOf('/'));
    final prefix = '${base.substring(dir.length + 1)}.';
    try {
      return [
        for (final f in Directory(dir).listSync().whereType<File>())
          if (f.uri.pathSegments.last case final name when _isSidecar(name, prefix)) '$dir/$name',
      ]..sort();
    } on FileSystemException {
      return const [];
    }
  }

  static bool _isSidecar(String name, String prefix) {
    if (!name.startsWith(prefix)) return false;
    final rest = name.substring(prefix.length);
    final dot = rest.lastIndexOf('.');
    final ext = rest.substring(dot + 1).toLowerCase();
    return _exts.contains(ext) && (dot == -1 || _lang.hasMatch(rest.substring(0, dot)));
  }

  static String _base(String path) {
    final dot = path.lastIndexOf('.');
    return dot > path.lastIndexOf('/') ? path.substring(0, dot) : path;
  }

  static String srt(Iterable<ClosedCaption> captions) {
    final out = StringBuffer();
    var n = 0;
    for (final c in captions) {
      final text = c.text.replaceAll('\r\n', '\n').trim();
      if (text.isEmpty) continue;
      out
        ..writeln(++n)
        ..writeln('${_time(c.offset)} --> ${_time(c.end)}')
        ..writeln(text)
        ..writeln();
    }
    return out.toString();
  }

  static String _time(Duration d) {
    String two(int v) => v.toString().padLeft(2, '0');
    return '${two(d.inHours)}:${two(d.inMinutes % 60)}:${two(d.inSeconds % 60)},'
        '${(d.inMilliseconds % 1000).toString().padLeft(3, '0')}';
  }
}
